function shuffleArray<T>(items: T[]): T[] {
  const copy = [...items];
  for (let i = copy.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    const tmp = copy[i];
    copy[i] = copy[j];
    copy[j] = tmp;
  }
  return copy;
}

/**
 * Builds a rich shuffled deck of 60 character cards sampled according to the
 * difficulty's `deckWeights`, avoiding immediate repeats and ensuring the
 * opening 4 cards contain at least 2 `'good'` and 1 `'bad'`/`'scam'`.
 */
export function buildShuffledDeck(difficulty: DifficultyId): CharacterProfile[] {
  const config = DIFFICULTY_CONFIGS[difficulty] ?? DIFFICULTY_CONFIGS.normal;
  const { good: goodW, bad: badW, scam: scamW } = config.deckWeights;
  const totalWeight = goodW + badW + scamW;

  const pools: Record<CharacterCategory, CharacterProfile[]> = {
    good: CHARACTERS.filter((c) => c.category === 'good'),
    bad: CHARACTERS.filter((c) => c.category === 'bad'),
    scam: CHARACTERS.filter((c) => c.category === 'scam'),
  };

  // Refillable shuffled bags per category so every character appears evenly before repeating
  const bags: Record<CharacterCategory, CharacterProfile[]> = {
    good: shuffleArray(pools.good),
    bad: shuffleArray(pools.bad),
    scam: shuffleArray(pools.scam),
  };

  const recentIds: string[] = [];
  const RECENT_WINDOW = 4;

  const drawFromCategory = (category: CharacterCategory): CharacterProfile => {
    if (bags[category].length === 0) {
      bags[category] = shuffleArray(pools[category]);
    }
    // Find the first candidate in the bag that isn't in recentIds
    let pickIndex = bags[category].findIndex((c) => !recentIds.includes(c.id));
    if (pickIndex === -1) {
      pickIndex = 0;
    }
    const [picked] = bags[category].splice(pickIndex, 1);
    recentIds.push(picked.id);
    if (recentIds.length > RECENT_WINDOW) {
      recentIds.shift();
    }
    return picked;
  };

  const pickWeightedCategory = (): CharacterCategory => {
    const r = Math.random() * totalWeight;
    if (r < goodW) return 'good';
    if (r < goodW + badW) return 'bad';
    return 'scam';
  };

  // Opening 4 cards: guarantee 2 'good', 1 'bad', 1 'scam' (or weighted 4th)
  const openingCategories: CharacterCategory[] = shuffleArray([
    'good',
    'good',
    Math.random() < 0.5 ? 'bad' : 'scam',
    pickWeightedCategory(),
  ]);

  const deck: CharacterProfile[] = [];
  const TARGET_DECK_SIZE = 60;

  for (let i = 0; i < TARGET_DECK_SIZE; i++) {
    const category =
      i < openingCategories.length ? openingCategories[i] : pickWeightedCategory();
    deck.push(drawFromCategory(category));
  }

  return deck;
}
